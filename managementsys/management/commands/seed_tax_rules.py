"""
seed_tax_rules
==============
Creates the starting set of Indonesian tax rules for /accounting/tax.
Idempotent — a rule that already exists is left alone unless --overwrite is
given, so an operator's edits are never silently reverted.

The rules seeded here are a *starting point sized to this clinic*, not tax
advice. Two of them deliberately need a human decision before they mean
anything:

  ppn_keluaran   Health services are largely VAT-exempt while retail product
                 sales are not, so the base is seeded as product revenue only.
                 If the clinic is not a PKP, deactivate the PPN rules entirely.
  ppn_masukan    Input VAT comes off supplier tax invoices, which the ledger
                 does not model yet. Seeded with no base at all — it computes
                 zero and visibly asks to be pointed at an account.

Rates and thresholds are stored as data. When a rate changes, edit the rule on
the page (or add a replacement with effective_from set); do not edit this file
and re-seed.

Usage:
    python manage.py seed_tax_rules
    python manage.py seed_tax_rules --overwrite
    python manage.py seed_tax_rules --dry-run
"""
