class Command(BaseCommand):
    help = 'Seed the default Indonesian tax rules for the taxation page.'

    def add_arguments(self, parser):
        parser.add_argument('--dry-run', action='store_true',
                            help='Report what would change without writing.')
        parser.add_argument('--overwrite', action='store_true',
                            help='Replace rules that already exist.')

    def handle(self, *args, **options):
        dry = options['dry_run']
        overwrite = options['overwrite']

        accounts = {a.account_number: a for a in ChartOfAccounts.objects.all()}
        created, skipped, replaced, warnings = [], [], [], []

        with transaction.atomic():
            by_code = {}
            for spec in RULES:
                code = spec['code']
                existing = TaxRule.objects.filter(code=code).first()
                if existing and not overwrite:
                    skipped.append(code)
                    by_code[code] = existing
                    continue
                if existing:
                    replaced.append(code)
                    existing.components.all().delete()
                    existing.brackets.all().delete()
                    rule = existing
                else:
                    created.append(code)
                    rule = TaxRule(code=code)

                rule.name = spec['name']
                rule.description = spec.get('description', '')
                rule.basis = spec.get('basis', 'period')
                rule.rate_mode = spec.get('rate_mode', 'flat')
                rule.rate_percent = spec.get('rate_percent', Decimal('0'))
                rule.deduction_amount = spec.get('deduction_amount', Decimal('0'))
                rule.rounding = spec.get('rounding', 'rupiah')
                rule.display_order = spec.get('display_order', 0)
                rule.notes = spec.get('notes', '')
                rule.facility_turnover_cap = spec.get('facility_turnover_cap', Decimal('0'))
                rule.facility_full_rate_cap = spec.get('facility_full_rate_cap', Decimal('0'))
                rule.facility_factor = spec.get('facility_factor', Decimal('0.5'))
                turnover_code = spec.get('facility_turnover_code')
                if turnover_code:
                    rule.facility_turnover_rule = by_code.get(turnover_code)
                    if rule.facility_turnover_rule is None:
                        warnings.append(
                            f'{code}: aturan omzet "{turnover_code}" belum ada.')
                rule.save()
                by_code[code] = rule

                for i, comp in enumerate(spec.get('components', [])):
                    account = None
                    if 'account_number' in comp:
                        account = accounts.get(comp['account_number'])
                        if account is None:
                            warnings.append(
                                f"{code}: akun {comp['account_number']} tidak ada, "
                                f'komponen dilewati.')
                            continue
                    source_rule = None
                    if comp.get('source_rule_code'):
                        source_rule = by_code.get(comp['source_rule_code'])
                        if source_rule is None:
                            warnings.append(
                                f"{code}: aturan {comp['source_rule_code']} belum ada, "
                                f'komponen dilewati.')
                            continue
                    TaxRuleComponent.objects.create(
                        rule=rule,
                        source=comp['source'],
                        sign=comp.get('sign', 1),
                        account=account,
                        account_type=comp.get('account_type', ''),
                        source_rule=source_rule,
                        label=comp.get('label', ''),
                        display_order=i,
                    )

                for i, number in enumerate(spec.get('component_accounts', [])):
                    account = accounts.get(number)
                    if account is None:
                        warnings.append(f'{code}: akun {number} tidak ada, dilewati.')
                        continue
                    TaxRuleComponent.objects.create(
                        rule=rule, source='account', sign=1, account=account,
                        label=f'{account.account_number} – {account.name}',
                        display_order=i,
                    )

                for i, (upper, rate) in enumerate(spec.get('brackets', [])):
                    TaxRuleBracket.objects.create(
                        rule=rule, upper_bound=upper, rate_percent=rate,
                        display_order=i,
                    )

            if dry:
                transaction.set_rollback(True)

        for code in created:
            self.stdout.write(self.style.SUCCESS(f'  + {code}'))
        for code in replaced:
            self.stdout.write(self.style.WARNING(f'  ~ {code} (diganti)'))
        for code in skipped:
            self.stdout.write(f'  = {code} (sudah ada, dilewati)')
        for warning in warnings:
            self.stdout.write(self.style.WARNING(f'  ! {warning}'))

        verb = 'akan dibuat' if dry else 'dibuat'
        self.stdout.write(self.style.SUCCESS(
            f'\n{len(created)} aturan {verb}, {len(replaced)} diganti, '
            f'{len(skipped)} dilewati.'))
        if dry:
            self.stdout.write(self.style.WARNING('DRY RUN — tidak ada yang disimpan.'))
